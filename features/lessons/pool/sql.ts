import type { PoolRecord } from "./records"

const CONTENT_TAG = "$content$"

/** A single-quoted SQL literal. Only used for values the records already restrict to [a-z0-9:-]. */
function text(value: string) {
  return `'${value.replaceAll("'", "''")}'`
}

function integer(value: number) {
  if (!Number.isInteger(value)) throw new Error(`${value} is not an integer`)
  return String(value)
}

/** Dollar-quoted, so the JSON is stored exactly as written, whatever its quotes and backslashes. */
function jsonb(value: unknown) {
  const json = JSON.stringify(value)
  if (json.includes(CONTENT_TAG))
    throw new Error(`Exercise content contains ${CONTENT_TAG}`)
  return `${CONTENT_TAG}${json}${CONTENT_TAG}::jsonb`
}

const COLUMNS = [
  "unit_id",
  "lesson_id",
  "lesson_position",
  "exercise_position",
  "exercise_type",
  "concept_tag",
  "content",
] as const

const list = (prefix: string) =>
  COLUMNS.map((column) => `${prefix}${column}`).join(", ")

/**
 * One transaction that brings public.exercises_pool in line with the records:
 * - new exercises are inserted and published
 * - changed exercises are updated and published again; unchanged rows are not touched at all
 * - published rows of an imported lesson that the source no longer has are unpublished, never deleted
 * - rows of lessons outside this import, base_difficulty and all learner data are left alone
 * It ends by selecting one row of counts. The same output is deterministic for the same records.
 */
export function ingestionSql(records: readonly PoolRecord[]) {
  if (records.length === 0) throw new Error("There is nothing to import.")
  const values = [...records]
    .sort((a, b) =>
      a.lesson_id === b.lesson_id
        ? a.exercise_position - b.exercise_position
        : a.lesson_id < b.lesson_id
          ? -1
          : 1
    )
    .map(
      (record) =>
        `  (${[
          text(record.source_key),
          text(record.unit_id),
          text(record.lesson_id),
          integer(record.lesson_position),
          integer(record.exercise_position),
          text(record.exercise_type),
          text(record.concept_tag),
          jsonb(record.content),
        ].join(", ")})`
    )
    .join(",\n")

  return `-- Generated by scripts/ingest-curriculum.ts from content/courses/de/lessons. Do not edit; regenerate it.
begin;

-- One import at a time. Learners can keep reading while it runs.
lock table public.exercises_pool in share row exclusive mode;

create temporary table exercises_pool_import (
  source_key text primary key,
  unit_id text not null,
  lesson_id text not null,
  lesson_position smallint not null,
  exercise_position smallint not null,
  exercise_type text not null,
  concept_tag text not null,
  content jsonb not null
) on commit drop;

insert into exercises_pool_import (source_key, ${list("")}) values
${values};

with incoming as (
  select
    i.*,
    p.id is null as is_new,
    p.id is not null
      and (${list("p.")}, p.is_active)
        is distinct from (${list("i.")}, true) as is_changed
  from exercises_pool_import i
  left join public.exercises_pool p using (source_key)
),
written as (
  insert into public.exercises_pool as pool (source_key, ${list("")}, is_active)
  select source_key, ${list("")}, true
  from incoming
  where is_new or is_changed
  on conflict (source_key) do update set
${COLUMNS.map((column) => `    ${column} = excluded.${column},`).join("\n")}
    is_active = true
  returning pool.source_key
),
retired as (
  update public.exercises_pool pool
  set is_active = false
  where pool.is_active
    and pool.lesson_id in (select lesson_id from exercises_pool_import)
    and pool.source_key not in (select source_key from exercises_pool_import)
  returning pool.source_key
)
select
  (select count(*) from incoming where is_new) as inserted,
  (select count(*) from incoming where is_changed) as updated,
  (select count(*) from incoming where not is_new and not is_changed) as unchanged,
  (select count(*) from retired) as unpublished,
  (select count(*) from written) as written,
  (
    select count(*) from public.exercises_pool p
    where p.is_active
      and p.lesson_id not in (select lesson_id from exercises_pool_import)
  ) as outside_import;

commit;
`
}

export type IngestionCounts = {
  inserted: number
  updated: number
  unchanged: number
  unpublished: number
  written: number
  outsideImport: number
}

/** Reads the counts row, as printed by psql -At ("1|2|3|4|5|6"). */
export function parseIngestionCounts(line: string): IngestionCounts | null {
  const parts = line.trim().split("|")
  if (parts.length !== 6 || parts.some((part) => !/^\d+$/.test(part)))
    return null
  const [inserted, updated, unchanged, unpublished, written, outsideImport] =
    parts.map(Number) as [number, number, number, number, number, number]
  return { inserted, updated, unchanged, unpublished, written, outsideImport }
}

/** All rows, published or not, as one JSON array, for the parity check. */
export const PARITY_QUERY = `select coalesce(json_agg(row_to_json(p) order by p.lesson_id, p.exercise_position), '[]'::json)
from (
  select source_key, unit_id, lesson_id, lesson_position, exercise_position,
    exercise_type, concept_tag, content, is_active
  from public.exercises_pool
) p;`
